"""
LiveKit browser-call endpoints.
GET  /call/{room_id}?exp=…&sig=…   → serves the call.html UI page, branded for the link's business
GET  /livekit/token?room=…&exp=…&sig=… → issues a short-lived LiveKit JWT for that one room

Both need the signed, expiring link generated by the WhatsApp "call me" flow
(core.signed_links). The old unauthenticated POST /livekit/send-whatsapp was removed — nothing
called it; the agent worker sends WhatsApp messages through the tool executor directly.
"""

import html
import json
import logging
import re
import uuid
from datetime import timedelta
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, HTTPException, Query, Request
from fastapi.responses import HTMLResponse, JSONResponse

from config import settings
from core import ratelimit
from core.signed_links import CALL_LINK_TTL_SECONDS, verify_call_room, verify_permanent
from core.tenancy import resolve_by_id
from core.tenancy.models import TenantConfig, legacy_hotel_tenant

logger = logging.getLogger(__name__)

livekit_router = APIRouter(tags=["LiveKit"])

CALL_HTML_PATH = Path(__file__).resolve().parent.parent / "ui" / "call.html"


# Per business type: icon, accent gradient, text colour on the accent, glow (r,g,b). Each pair keeps the
# button label at 4.5:1 or better against both ends of its gradient.
_THEMES: dict[str, tuple[str, str, str, str, str]] = {
    "hotel":         ("🏨", "#f7971e", "#ffd200", "#1a1a1a", "247,151,30"),
    "dental":        ("🦷", "#14b8a6", "#2dd4bf", "#04201d", "20,184,166"),
    "clinic":        ("🩺", "#0ea5e9", "#38bdf8", "#031525", "14,165,233"),
    "salon":         ("💇", "#9d174d", "#be185d", "#ffffff", "190,24,93"),
    "restaurant":    ("🍽️", "#f97316", "#fdba74", "#1f0a00", "249,115,22"),
    "home_services": ("🔧", "#1d4ed8", "#2563eb", "#ffffff", "37,99,235"),
    "professional":  ("💼", "#4338ca", "#6366f1", "#ffffff", "99,102,241"),
    "generic":       ("📞", "#14b8a6", "#2dd4bf", "#04201d", "20,184,166"),
}


async def _link_tenant(request: Request, ref: str, permanent: bool) -> tuple[Optional[TenantConfig], str]:
    """The business a call link belongs to, after checking the link: (tenant, problem message or "")."""
    q = request.query_params
    if permanent:
        if not verify_permanent(ref, q.get("k")):
            return None, "This call link is invalid or has been turned off."
        tenant_id = None if ref == "default" else ref
    else:
        try:
            exp = int(q.get("exp") or 0)
        except ValueError:
            exp = 0
        tenant_id = q.get("t") or None
        if not verify_call_room(ref, exp, q.get("sig"), tenant_id=tenant_id):
            return None, "This call link is invalid or has expired. Please ask for a new link."
    tenant = (await resolve_by_id(tenant_id)) if tenant_id else legacy_hotel_tenant()
    if tenant is None:
        return None, "This business is no longer available."
    return tenant, ""


def _render_call_page(tenant: Optional[TenantConfig], problem: str) -> HTMLResponse:
    """call.html with the business's name, assistant and look filled in, so it never shows another's."""
    if not CALL_HTML_PATH.exists():
        logger.error("call.html not found at %s", CALL_HTML_PATH)
        raise HTTPException(status_code=500, detail="Call UI page not found on server")
    vertical = tenant.vertical if tenant else "generic"
    icon, a1, a2, on_accent, glow = _THEMES.get(vertical, _THEMES["generic"])
    business = tenant.name if tenant else "Live call"
    agent = (tenant.agent.name or "").strip() if tenant else ""
    agent_label = agent or "The assistant"
    if tenant:
        subtitle = f"Talk to {agent}, {business}'s virtual assistant" if agent else f"Talk to {business}'s virtual assistant"
        tip = "Allow microphone access when prompted, then speak naturally — just like phoning us."
    else:
        subtitle, tip = "", ""
    brand = {"business": business, "agent": agent_label, "problem": problem}
    values = {
        "LANG": html.escape((tenant.locale if tenant else "") or "en"),
        "TITLE": html.escape(f"{business} — Live Call" if tenant else "Live call"),
        "THEME": (f"<style>:root{{--a1:{a1};--a2:{a2};--on-accent:{on_accent};--glow:{glow};}}</style>"),
        "ICON": icon,
        "NAME": html.escape(business),
        "SUBTITLE": html.escape(subtitle),
        "AGENT": html.escape(agent_label),
        "TIP": html.escape(tip),
        # Inside a <script> tag: escape "<" so a business name can't close it.
        "BRAND_JSON": json.dumps(brand).replace("<", "\\u003c"),
    }
    page = re.sub(r"__(" + "|".join(values) + r")__", lambda m: values[m.group(1)],
                  CALL_HTML_PATH.read_text(encoding="utf-8"))
    return HTMLResponse(page, headers={"Cache-Control": "no-store", "Referrer-Policy": "no-referrer"})


@livekit_router.get("/call/{room_id}")
async def call_page(room_id: str, request: Request):
    """The call UI for a signed, expiring link. The page carries no secrets; the token endpoint checks again."""
    return _render_call_page(*await _link_tenant(request, room_id, permanent=False))


@livekit_router.get("/talk/{tenant_ref}")
async def talk_page(tenant_ref: str, request: Request):
    """The permanent call page for one business (/talk/<tenant id or "default">?k=<key>). Same UI as /call."""
    return _render_call_page(*await _link_tenant(request, tenant_ref, permanent=True))


def livekit_configured() -> bool:
    return bool(settings.LIVEKIT_API_KEY and settings.LIVEKIT_API_SECRET and settings.LIVEKIT_URL)


def mint_browser_token(tenant: TenantConfig, room: str, attributes: Optional[dict[str, str]] = None,
                       ttl_s: int = CALL_LINK_TTL_SECONDS) -> tuple[str, str]:
    """A LiveKit JWT that lets one browser join `room` with a microphone and summons the receptionist
    for `tenant`. Returns (jwt, identity). Raises 503 when LiveKit isn't configured."""
    if not livekit_configured():
        logger.error("LiveKit not configured (LIVEKIT_URL / LIVEKIT_API_KEY / LIVEKIT_API_SECRET)")
        raise HTTPException(status_code=503, detail="Calling is temporarily unavailable.")

    from livekit import api

    identity = f"guest_{uuid.uuid4().hex[:8]}"  # server-chosen; never trust a client identity
    token = (
        api.AccessToken(settings.LIVEKIT_API_KEY, settings.LIVEKIT_API_SECRET)
        .with_identity(identity)
        .with_ttl(timedelta(seconds=ttl_s))
        # Server-signed, so the worker can trust it: which business this browser call is for (and,
        # for the landing-page demo, which lead). The tenant id always wins over extra attributes.
        .with_attributes({**(attributes or {}), "tenant_id": tenant.id})
        .with_grants(api.VideoGrants(
            room_join=True,
            room=room,                # this room only
            can_publish=True,         # microphone
            can_subscribe=True,
            can_publish_data=False,
        ))
        # The worker registers under an explicit agent name, so rooms aren't auto-dispatched:
        # joining with this token asks LiveKit to send the receptionist into the room.
        .with_room_config(api.RoomConfiguration(
            agents=[api.RoomAgentDispatch(agent_name=settings.LIVEKIT_AGENT_NAME)],
        ))
        .to_jwt()
    )
    return token, identity


async def _allow_public_call(request: Request) -> bool:
    # Shared by every API replica (Redis). The daily cap covers all visitors together, so a forged
    # client-IP header can only dodge the per-visitor limit.
    return (await ratelimit.allow("pubcall:all", settings.PUBLIC_CALL_MAX_PER_DAY, 86400)
            and await ratelimit.allow(f"pubcall:ip:{ratelimit.client_ip(request)}",
                                      settings.PUBLIC_CALL_RATE_PER_IP_HOUR, 3600))


@livekit_router.get("/livekit/token")
async def livekit_token(
    request: Request,
    room: Optional[str] = Query(default=None, min_length=3, max_length=64),
    exp: Optional[int] = Query(default=None),
    sig: Optional[str] = Query(default=None, max_length=64),
    t: Optional[str] = Query(default=None, max_length=40, description="tenant id the link was signed for"),
    perm: Optional[str] = Query(default=None, max_length=64, description="key of a permanent /talk link"),
):
    if perm is not None:
        # Permanent link: no expiry, so the visitor gets a brand-new room and the call is rate limited.
        ref = t or "default"
        if not verify_permanent(ref, perm):
            raise HTTPException(status_code=403, detail="This call link is invalid or has been turned off.")
        if not await _allow_public_call(request):
            raise HTTPException(status_code=429, detail="The receptionist is busy right now. Please try again later.")
        room = f"web-{uuid.uuid4().hex[:10]}"
        t = None if ref == "default" else ref
    else:
        if not room:
            raise HTTPException(status_code=422, detail="room is required")
        if not verify_call_room(room, exp, sig, tenant_id=t):
            raise HTTPException(status_code=403, detail="This call link is invalid or has expired.")
    tenant = (await resolve_by_id(t)) if t else legacy_hotel_tenant()
    if tenant is None:
        raise HTTPException(status_code=404, detail="This business is no longer available.")

    token, identity = mint_browser_token(tenant, room)

    return JSONResponse({
        "token": token,
        "url": settings.LIVEKIT_URL,
        "room": room,
        "identity": identity,
        "hotel_name": tenant.name,
        "business_name": tenant.name,
        "receptionist_name": tenant.agent.name,
        "hotel_phone": tenant.phone,
    }, headers={"Cache-Control": "no-store"})
